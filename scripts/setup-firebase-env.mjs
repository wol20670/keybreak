/**
 * Copies the three values KEYBREAK needs out of a Firebase service account
 * JSON file into .env.
 *
 * Run with:  npm run env:firebase
 *
 * Secret discipline: this script never prints a value. It reports key names,
 * lengths and booleans only, so it is safe to run with the output visible.
 */
import { readFile, writeFile, access } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const accountPath = join(root, "firebase-service-account.json");
const envPath = join(root, ".env");

let account;
try {
  account = JSON.parse(await readFile(accountPath, "utf8"));
} catch {
  console.error(
    "Could not read firebase-service-account.json at the project root.\n" +
      "Firebase Console -> Project settings -> Service accounts -> Generate new private key,\n" +
      "then save the downloaded file as firebase-service-account.json here.",
  );
  process.exit(1);
}

const missing = ["project_id", "client_email", "private_key"].filter(
  (field) => !account[field],
);
if (missing.length) {
  console.error(`Service account JSON is missing: ${missing.join(", ")}`);
  process.exit(1);
}

const vars = {
  FIREBASE_PROJECT_ID: account.project_id,
  FIREBASE_CLIENT_EMAIL: account.client_email,
  // Stored as a quoted single line with escaped newlines so the value survives
  // .env parsing. lib/firebase.ts converts it back.
  FIREBASE_PRIVATE_KEY: account.private_key,
};

let existing = "";
try {
  await access(envPath);
  existing = await readFile(envPath, "utf8");
} catch {
  // No .env yet — it will be created.
}

// Preserve every line that is not one of ours, so an existing .env is not lost.
const kept = existing
  .split(/\r?\n/)
  .filter((line) => !Object.keys(vars).some((key) => line.startsWith(`${key}=`)))
  .join("\n")
  .replace(/\n{3,}/g, "\n\n")
  .trim();

const rendered = Object.entries(vars)
  .map(([key, value]) =>
    key === "FIREBASE_PRIVATE_KEY"
      ? `${key}="${value.replace(/\n/g, "\\n")}"`
      : `${key}=${value}`,
  )
  .join("\n");

await writeFile(
  envPath,
  `${kept ? `${kept}\n\n` : ""}# Firebase Admin (server only) — generated by npm run env:firebase\n${rendered}\n`,
  "utf8",
);

console.log("Wrote .env:");
for (const [key, value] of Object.entries(vars)) {
  console.log(`  ${key} set (${String(value).length} chars)`);
}
console.log(
  `  private key parses as PEM: ${/^-----BEGIN [A-Z ]*PRIVATE KEY-----/.test(
    vars.FIREBASE_PRIVATE_KEY.trim(),
  )}`,
);
console.log("\n.env is gitignored. No values were printed.");
